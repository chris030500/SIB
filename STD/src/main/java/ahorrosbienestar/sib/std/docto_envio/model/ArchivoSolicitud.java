package ahorrosbienestar.sib.std.docto_envio.model;

public class ArchivoSolicitud {
	
	private int idDoctoEnvio;
	private String rutaDoct;
	private String nombreArchivo;
	
	public int getIdDoctoEnvio() {
		return idDoctoEnvio;
	}
	public void setIdDoctoEnvio(int idDoctoEnvio) {
		this.idDoctoEnvio = idDoctoEnvio;
	}
	public String getRutaDoct() {
		return rutaDoct;
	}
	public void setRutaDoct(String rutaDoct) {
		this.rutaDoct = rutaDoct;
	}
	public String getNombreArchivo() {
		return nombreArchivo;
	}
	public void setNombreArchivo(String nombreArchivo) {
		this.nombreArchivo = nombreArchivo;
	}
	
	
	
	
}
