package ahorrosbienestar.sib.std.operaciones.seguimientoGestion.listaSeguimiento.repository;

import java.util.List;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;
import ahorrosbienestar.sib.std.operaciones.seguimientoGestion.listaSeguimiento.model.EstatusSeguimientoModel;

@Repository
public interface EstatusSeguimientoRepository extends JpaRepository<EstatusSeguimientoModel, Integer> {
	
	@Query(value = "SELECT "
			+ "     ctE.PK_ID,"
			+ "     ctE.V_VALOR,"
			+ "     COUNT(*) AS TOTAL_REGISTROS"
			+ " FROM ("
			+ " select tblCampanias.I_CLIENTEID"
			+ " ,aoa.PK_ID_ASIGNACION_OA"
			+ " ,aoa.I_BLOQUEO"
			+ " ,tblCampanias.VC_NombreCompleto as nombreCompleto"
			+ " ,tblOA.VC_CODIGO_OFERTA"
			+ " ,aoa.VC_COD_REFERENCIA"
			+ " ,date_format(aoa.DT_FECHA_ASIGNACION, '%Y-%m-%d') FECHAINICIO"
			+ " ,date_format(aoa.DT_FECHA_VIGENCIA, '%Y-%m-%d') FECHAFIN"
			+ " ,aoa.i_estatus"
			+ " ,aoa.FK_ID_SUCURSAL"
			+ " FROM SIB.TBL_ASIGNACION_OFERTAS aoa"
			+ " inner join SIB.TBL_OFERTAS_AUTOMATICAS tblOA on aoa.fk_id_ofertas_automaticas = tblOA.pk_id_ofertas_automaticas"
			+ " inner join SIB.TBL_BASE_CAMPANIAS_VIP_HIST tblCampanias on tblCampanias.I_CLIENTEID = tblOA.I_CLIENTEID and tblOA.ID_REG_BASE = tblCampanias.PK_ID_BASE_CAMPANIAS"
			+ " INNER JOIN SIB.TBL_CLASIFICACION_BASES_OA tblsClass on tblsClass.PK_ID_CLASIFICACION = tblOA.I_COD_CLASIFICACION"
			+ " WHERE tblOA.C_ESTATUS_OFERTA = 'A'  and aoa.I_ACTIVO=1"
			+ " union all "
			+ " select tblFide.I_CLIENTE_ID"
			+ " ,aoa.PK_ID_ASIGNACION_OA"
			+ " ,aoa.I_BLOQUEO"
			+ " ,tblFide.VC_NOMBRE_COMPLETO_CLIENTE as nombreCompleto"
			+ " ,tblOA.VC_CODIGO_OFERTA"
			+ " ,aoa.VC_COD_REFERENCIA"
			+ " ,date_format(aoa.DT_FECHA_ASIGNACION, '%Y-%m-%d') FECHAINICIO"
			+ " ,date_format(aoa.DT_FECHA_VIGENCIA, '%Y-%m-%d') FECHAFIN"
			+ " ,aoa.i_estatus"
			+ " ,aoa.FK_ID_SUCURSAL"
			+ " FROM SIB.TBL_ASIGNACION_OFERTAS aoa"
			+ " inner join  SIB.TBL_OFERTAS_AUTOMATICAS tblOA  on aoa.fk_id_ofertas_automaticas = tblOA.pk_id_ofertas_automaticas"
			+ " inner join SIB.TBL_FIDELIDAD_OA tblFide on tblFide.I_CLIENTE_ID = tblOA.I_CLIENTEID and tblOA.ID_REG_BASE = tblFide.PK_ID_FIDELIDAD"
			+ " INNER JOIN SIB.TBL_CLASIFICACION_BASES_OA tblsClass on tblsClass.PK_ID_CLASIFICACION = tblOA.I_COD_CLASIFICACION"
			+ " WHERE tblOA.C_ESTATUS_OFERTA = 'A'  and aoa.I_ACTIVO=1"
			+ " union all "
			+ " select tblsL.I_CLIENTEID"
			+ " ,aoa.PK_ID_ASIGNACION_OA"
			+ " ,aoa.I_BLOQUEO"
			+ " ,tblsL.VC_NOMBRECOMPLETO as nombreCompleto"
			+ " ,tblOA.VC_CODIGO_OFERTA"
			+ " ,aoa.VC_COD_REFERENCIA"
			+ " ,date_format(aoa.DT_FECHA_ASIGNACION, '%Y-%m-%d') FECHAINICIO"
			+ " ,date_format(aoa.DT_FECHA_VIGENCIA, '%Y-%m-%d') FECHAFIN"
			+ " ,aoa.i_estatus"
			+ " ,aoa.FK_ID_SUCURSAL"
			+ " FROM SIB.TBL_ASIGNACION_OFERTAS aoa"
			+ " INNER JOIN SIB.TBL_OFERTAS_AUTOMATICAS tblOA on aoa.fk_id_ofertas_automaticas = tblOA.pk_id_ofertas_automaticas"
			+ " INNER JOIN SIB.TBL_NOMINA_LIQUIDADOS tblsL on tblsL.I_CLIENTEID = tblOA.I_CLIENTEID AND tblOA.ID_REG_BASE = tblsL.PK_ID_LIQUIDADOS"
			+ " INNER JOIN SIB.TBL_CLASIFICACION_BASES_OA tblsClass on tblsClass.PK_ID_CLASIFICACION = tblOA.I_COD_CLASIFICACION"
			+ " WHERE tblOA.C_ESTATUS_OFERTA = 'A'  and aoa.I_ACTIVO=1"
			+ " union all"
			+ " select "
			+ " tblsNL.I_CLIENTE_ID"
			+ " ,aoa.I_BLOQUEO"
			+ " ,aoa.PK_ID_ASIGNACION_OA"
			+ " ,tblsNL.VC_NOMBRE_COMPLETO as nombreCompleto"
			+ " ,tblOA.VC_CODIGO_OFERTA"
			+ " ,aoa.VC_COD_REFERENCIA"
			+ " ,date_format(aoa.DT_FECHA_ASIGNACION, '%Y-%m-%d') FECHAINICIO"
			+ " ,date_format(aoa.DT_FECHA_VIGENCIA, '%Y-%m-%d') FECHAFIN"
			+ " ,aoa.i_estatus"
			+ " ,aoa.FK_ID_SUCURSAL"
			+ " FROM SIB.TBL_ASIGNACION_OFERTAS aoa"
			+ " INNER JOIN SIB.TBL_OFERTAS_AUTOMATICAS tblOA on aoa.fk_id_ofertas_automaticas = tblOA.pk_id_ofertas_automaticas"
			+ " INNER JOIN SIB.TBL_NOMINA_NLIQUIDADOS tblsNL on tblsNL.I_CLIENTE_ID = tblOA.I_CLIENTEID AND tblOA.ID_REG_BASE = tblsNL.PK_ID_NLIQUIDADOS"
			+ " INNER JOIN SIB.TBL_CLASIFICACION_BASES_OA tblsClass on tblsClass.PK_ID_CLASIFICACION = tblOA.I_COD_CLASIFICACION"
			+ " WHERE tblOA.C_ESTATUS_OFERTA = 'A' and aoa.I_ACTIVO=1) tB"
			+ " INNER JOIN SIB.TBL_SUCURSALES suc ON suc.PK_ID_SUCURSAL = tB.FK_ID_SUCURSAL"
			+ " INNER JOIN SIB.TBL_OPC_BUSQUEDA ctE ON ctE.I_OPCION = tB.i_estatus AND ctE.I_ID_GRUPO = '14'"
			+ " WHERE suc.PK_ID_SUCURSAL = :sucursal"
			+ " GROUP BY ctE.PK_ID", nativeQuery = true)
	public List<EstatusSeguimientoModel> listaDeEstatus(@Param("sucursal") int sucursal);

}
